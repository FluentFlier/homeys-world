export function getListingCoords(neighborhood: string | null, citySlug: string): [number, number] | null {
  if (neighborhood && COORDS[citySlug]?.[neighborhood]) {
    return COORDS[citySlug][neighborhood]
  }
  if (CITY_CENTERS[citySlug]) {
    // Add slight random offset so pins don't stack exactly
    const center = CITY_CENTERS[citySlug]
    const offset = () => (Math.random() - 0.5) * 0.01
    return [center[0] + offset(), center[1] + offset()]
  }
  return null
}
